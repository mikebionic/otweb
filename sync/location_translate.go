// provinceSuffixes - суффиксы административных единиц для поиска границ.
var provinceSuffixes = []string{"壮族自治区", "回族自治区", "维吾尔自治区", "自治区", "特别行政区", "省", "市"}

// citySuffixes - суффиксы городов.
var citySuffixes = []string{"市", "区", "县"}

// stripSuffix убирает один суффикс административной единицы.
func stripSuffix(s string) string {
	all := append(provinceSuffixes, citySuffixes...)
	for _, suf := range all {
		if strings.HasSuffix(s, suf) {
			return strings.TrimSuffix(s, suf)
		}
	}
	return s
}

// extractProvince извлекает провинцию из строки вида "广东省东莞市" → "广东".
// Возвращает (ключ для карты, остаток строки после провинции).
func extractProvince(s string) (string, string) {
	for _, suf := range provinceSuffixes {
		idx := strings.Index(s, suf)
		if idx > 0 {
			prov := s[:idx]
			rest := s[idx+len(suf):]
			return prov, rest
		}
	}
	return s, ""
}

// extractCity извлекает город из строки вида "东莞市" или "广东省东莞市".
func extractCity(s string) string {
	// Если строка содержит провинцию, берём часть после неё
	_, rest := extractProvince(s)
	if rest != "" {
		s = rest
	}
	// Убираем суффикс
	for _, suf := range citySuffixes {
		if strings.HasSuffix(s, suf) {
			return strings.TrimSuffix(s, suf)
		}
	}
	return s
}

// TranslateState переводит провинцию. Принимает как "广东省" так и "广东省东莞市".
// Возвращает перевод или пустую строку.
func TranslateState(cn string) string {
	if cn == "" {
		return ""
	}
	prov, _ := extractProvince(cn)
	if ru, ok := chineseProvinces[prov]; ok {
		return ru
	}
	// fallback: прямое совпадение
	if ru, ok := chineseProvinces[cn]; ok {
		return ru
	}
	return ""
}

// TranslateCity переводит город. Принимает как "东莞市" так и "广东省东莞市".
// Возвращает перевод или пустую строку.
func TranslateCity(cn string) string {
	if cn == "" {
		return ""
	}
	city := extractCity(cn)
	if ru, ok := chineseCities[city]; ok {
		return ru
	}
	if ru, ok := chineseCities[cn]; ok {
		return ru
	}
	return ""
}
