// IsColorAttr — относится ли название атрибута к цвету.
func IsColorAttr(name string) bool {
	n := strings.ToLower(name)
	return strings.Contains(n, "цвет") || strings.Contains(n, "color") || strings.Contains(n, "色")
}

// ColorHex возвращает HEX для значения-цвета (по подстроке) или "" если цвет не распознан.
func ColorHex(value string) string {
	v := strings.ToLower(value)
	for _, c := range colorHexOrder {
		if strings.Contains(v, c.Name) {
			return c.Hex
		}
	}
	return ""
}
